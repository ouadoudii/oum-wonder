import { readFile, writeFile } from 'node:fs/promises'

const engine = (await readFile('public/designEngine.js', 'utf8'))
  .replace(/export function createConcept/, 'function createConcept')
const image = (await readFile('public/imageAnalysis.js', 'utf8'))
  .replace(/export const neutralSignals/, 'const neutralSignals')
  .replace(/export async function analyseImage/, 'async function analyseImage')
const app = (await readFile('public/app.js', 'utf8'))
  .replace(/^import .*?;?\n/gm, '')
const previewCompare = await readFile('public/previewCompare.js', 'utf8')
const exportPlan = (await readFile('public/exportPlan.js', 'utf8'))
  .replace(/export function formatPlanText/, 'function formatPlanText')
  .replace(/export function buildPlanText/, 'function buildPlanText')
const spatialLight = (await readFile('public/spatialLight.js', 'utf8'))
  .replace(/export function analyseLightDistribution/, 'function analyseLightDistribution')
  .replace(/export function describeLightDistribution/, 'function describeLightDistribution')
const roomMeasurements = (await readFile('public/roomMeasurements.js', 'utf8'))
  .replace(/export function analyseRoomMeasurements/, 'function analyseRoomMeasurements')
const roomConstraints = (await readFile('public/roomConstraints.js', 'utf8'))
  .replace(/export function buildConstraintInsight/, 'function buildConstraintInsight')
const windowOrientation = (await readFile('public/windowOrientation.js', 'utf8'))
  .replace(/export function buildOrientationInsight/, 'function buildOrientationInsight')
const everydayNeeds = (await readFile('public/everydayNeeds.js', 'utf8'))
  .replace(/export function buildEverydayNeedsInsight/, 'function buildEverydayNeedsInsight')
const budgetCeiling = (await readFile('public/budgetCeiling.js', 'utf8'))
  .replace(/export function buildBudgetCeilingInsight/, 'function buildBudgetCeilingInsight')
const rentalFriendly = (await readFile('public/rentalFriendly.js', 'utf8'))
  .replace(/export function buildRentalFriendlyInsight/, 'function buildRentalFriendlyInsight')
  .replace(/export function buildRentalAlternatives/, 'function buildRentalAlternatives')

await writeFile('public/bundle.js', `${engine}\n${image}\n${app}\n${previewCompare}\n${exportPlan}\n${spatialLight}\n${roomMeasurements}\n${roomConstraints}\n${windowOrientation}\n${everydayNeeds}\n${budgetCeiling}\n${rentalFriendly}`)